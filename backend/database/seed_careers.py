def _enrich():
    for c in CAREERS:
        meta = CATEGORY_META.get(
            c["category"],
            {"classes": ["12th", "Graduation"], "streams": [], "domain": c["category"]},
        )
        c["classes"] = meta["classes"]
        c["streams"] = meta["streams"]
        c["domains"] = [meta["domain"]]


